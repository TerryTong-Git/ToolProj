#!/usr/bin/env python3
"""Aggregate ablation experiment results from JSON files into a structured CSV.

This script processes the individual JSON files generated by main.py during
embedding model ablation experiments and creates a comprehensive results table.
"""

import json
import logging
from pathlib import Path
from typing import Any

import pandas as pd

logging.basicConfig(level=logging.INFO, format="%(asctime)s - %(levelname)s - %(message)s")
logger = logging.getLogger(__name__)


def extract_result_summary(json_path: Path) -> dict[str, Any] | None:
    """Extract the result summary from a predictions JSON file.

    The JSON file contains a list where the last element is the summary dict.
    """
    try:
        with open(json_path, encoding="utf-8") as f:
            data = json.load(f)

        # Last element is the summary
        if not data:
            return None

        summary = data[-1]

        # Validate it's a summary dict (has required keys)
        required_keys = {"accuracy", "cross_entropy_bits", "feats"}
        if not required_keys.issubset(summary.keys()):
            logger.warning(f"Invalid summary in {json_path}")
            return None

        # Extract model and seed from filename or first record
        if len(data) > 1:
            first_record = data[0]
            summary["model"] = first_record.get("model", "unknown")
            summary["seed"] = first_record.get("seed", "0")
            summary["run_ts"] = first_record.get("run_ts", "")

        return summary

    except Exception as e:
        logger.error(f"Error processing {json_path}: {e}")
        return None


def aggregate_results(results_dir: str | Path, output_path: str | Path | None = None) -> pd.DataFrame:
    """Aggregate all JSON result files into a single DataFrame.

    Args:
        results_dir: Directory containing JSON result files
        output_path: Optional path to save CSV output

    Returns:
        DataFrame with aggregated results
    """
    results_dir = Path(results_dir)
    json_files = list(results_dir.glob("*.json"))
    logger.info(f"Found {len(json_files)} JSON files in {results_dir}")

    summaries = []
    for json_path in json_files:
        summary = extract_result_summary(json_path)
        if summary:
            summaries.append(summary)

    if not summaries:
        logger.warning("No valid summaries found")
        return pd.DataFrame()

    df = pd.DataFrame(summaries)

    # Reorder columns for readability
    priority_cols = [
        "model",
        "rep_filter",
        "seed",
        "feats",
        "embed_model",
        "accuracy",
        "mutual_info_lower_bound_bits",
        "cross_entropy_bits",
        "empirical_entropy_bits",
        "n_classes",
        "n_train",
        "n_test",
        "macro_f1",
    ]
    existing_priority = [c for c in priority_cols if c in df.columns]
    other_cols = [c for c in df.columns if c not in priority_cols]
    df = df[existing_priority + other_cols]

    # Sort by model, embed_model, rep, seed
    sort_cols = [c for c in ["model", "embed_model", "rep_filter", "seed"] if c in df.columns]
    if sort_cols:
        df = df.sort_values(sort_cols).reset_index(drop=True)

    if output_path:
        output_path = Path(output_path)
        output_path.parent.mkdir(parents=True, exist_ok=True)
        df.to_csv(output_path, index=False)
        logger.info(f"Saved aggregated results to {output_path}")

    return df


